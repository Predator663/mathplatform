def _fill(hexcolor):
    return PatternFill('solid', fgColor=hexcolor)


def _thin_border():
    s = Side(style='thin', color='FFD1D5DB')
    return Border(left=s, right=s, top=s, bottom=s)


def _write_xl_header(ws, classroom, extra, doc_title, ncols):
    row = 1
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row, 1, extra['school_name'])
    c.font = Font(bold=True, color='FFFFFFFF', size=13)
    c.fill = _fill('FF1e3a5f')
    c.alignment = Alignment(horizontal='center')
    ws.row_dimensions[row].height = 22
    row += 1

    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row, 1, doc_title)
    c.font = Font(bold=True, color='FFFFFFFF', size=11)
    c.fill = _fill('FF2d4f7c')
    c.alignment = Alignment(horizontal='center')
    row += 1

    # Each meta field (Class / Grade Level / Subject / Term / Generated…)
    # gets its own labelled "card" row — a coloured label chip on the
    # left, its value on the right — instead of one plain italic
    # sentence per field. Colour keyed by field type so it visually
    # matches the same palette used across the app (blue = class info,
    # violet = grade level, green = subject, amber = term).
    FIELD_COLORS = {
        'CLASS':          ('FFDCEAFE', 'FF1D4ED8'),
        'GRADE LEVEL':     ('FFEDE9FE', 'FF6D28D9'),
        'ACADEMIC YEAR':   ('FFF3F4F6', 'FF374151'),
        'SUBJECT':         ('FFD1FAE5', 'FF047857'),
        'TERM':            ('FFFEF3C7', 'FFB45309'),
        'GENERATED':       ('FFF3F4F6', 'FF6B7280'),
        'GENERATED BY':    ('FFF3F4F6', 'FF6B7280'),
    }
    label_span = max(1, ncols // 3)
    for label, value in _meta_pairs(classroom, extra):
        bg, fg = FIELD_COLORS.get(label, ('FFF3F4F6', 'FF374151'))
        ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=label_span)
        lc = ws.cell(row, 1, label)
        lc.font = Font(bold=True, color=fg, size=8)
        lc.fill = _fill(bg)
        lc.alignment = Alignment(horizontal='left', indent=1, vertical='center')
        ws.merge_cells(start_row=row, start_column=label_span + 1, end_row=row, end_column=ncols)
        vc = ws.cell(row, label_span + 1, value)
        vc.font = Font(bold=True, color='FF111827', size=9.5)
        vc.fill = _fill('FFFFFFFF')
        vc.alignment = Alignment(horizontal='left', indent=1, vertical='center')
        for col in range(1, ncols + 1):
            ws.cell(row, col).border = _thin_border()
        ws.row_dimensions[row].height = 18
        row += 1
    return row + 1  # next free row


def _write_xl_footer(ws, row, ncols):
    ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
    c = ws.cell(row, 1, FOOTER_TEXT)
    c.font = Font(bold=True, italic=True, color='FF6b7280', size=9)
    c.alignment = Alignment(horizontal='center')
    # Also set as the printed page footer so it appears on every printed page.
    ws.oddFooter.center.text = FOOTER_TEXT
    ws.oddFooter.center.size = 9
    ws.evenFooter.center.text = FOOTER_TEXT


def generate_groups_summary_excel(classroom, groups: list, extra: dict) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = 'Group Summary'
    ncols = 7
    headers = ['Group', 'Members', 'Very Strong', 'Strong', 'Average', 'Weak', 'Group Avg %']
    row = _write_xl_header(ws, classroom, extra, 'Group Summary', ncols)

    for i, h in enumerate(headers, start=1):
        c = ws.cell(row, i, h)
        c.font = Font(bold=True, color='FFFFFFFF', size=10)
        c.fill = _fill('FF111827')
        c.alignment = Alignment(horizontal='center')
        c.border = _thin_border()
    row += 1

    def _avg_fill_font(pct):
        if pct is None:
            return None, Font(color='FF6b7280')
        if pct >= 65: return _fill('FFecfdf5'), Font(color='FF10b981', bold=True)
        if pct >= 45: return _fill('FFfffbeb'), Font(color='FFf59e0b', bold=True)
        return _fill('FFfef2f2'), Font(color='FFf43f5e', bold=True)

    TIER_TEXT = {
        'very_strong': 'FF10b981', 'strong': 'FF2563eb', 'average': 'FFf59e0b', 'weak': 'FFf43f5e',
    }
    for r_i, g in enumerate(groups):
        counts = {'very_strong': 0, 'strong': 0, 'average': 0, 'weak': 0}
        avgs = []
        for m in g.memberships.all():
            if m.tier in counts:
                counts[m.tier] += 1
            if m.average_at_placement is not None:
                avgs.append(m.average_at_placement)
        group_avg = round(sum(avgs) / len(avgs), 1) if avgs else None
        values = [g.name, g.memberships.count(), counts['very_strong'], counts['strong'],
                  counts['average'], counts['weak'], f'{group_avg}%' if group_avg is not None else '—']
        # Faint zebra striping using each group's own badge colour, tinted
        # very light, so the whole sheet isn't a wall of black-on-white.
        zebra = _fill('FFF9FAFB') if r_i % 2 else None
        for i, v in enumerate(values, start=1):
            c = ws.cell(row, i, v)
            c.border = _thin_border()
            c.alignment = Alignment(horizontal='center' if i > 1 else 'left')
            if zebra and i not in (3, 4, 5, 6, 7):
                c.fill = zebra
        # Bold group name, and colour each tier-count column to match the
        # same palette used everywhere else in-app.
        ws.cell(row, 1).font = Font(bold=True, color='FF111827')
        for col, tier in zip((3, 4, 5, 6), ('very_strong', 'strong', 'average', 'weak')):
            ws.cell(row, col).font = Font(bold=True, color=TIER_TEXT[tier])
        avg_fill, avg_font = _avg_fill_font(group_avg)
        avg_cell = ws.cell(row, 7)
        avg_cell.font = avg_font
        if avg_fill:
            avg_cell.fill = avg_fill
        row += 1

    row += 1
    _write_xl_footer(ws, row, ncols)

    widths = [26, 12, 14, 12, 12, 10, 14]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def generate_group_work_analytics_excel(classroom, analytics: dict, extra: dict) -> bytes:
    """Three sheets: By Group, By Stream, Trend — the Excel counterpart
    of the Group Work Analytics page, one tab per rollup."""
    wb = Workbook()

    def _pct_fill_font(pct):
        if pct is None:
            return None, Font(color='FF6b7280')
        if pct >= 65: return _fill('FFecfdf5'), Font(color='FF10b981', bold=True)
        if pct >= 45: return _fill('FFfffbeb'), Font(color='FFf59e0b', bold=True)
        return _fill('FFfef2f2'), Font(color='FFf43f5e', bold=True)

    # ── Sheet 1: By Group ────────────────────────────────────────────
    ws = wb.active
    ws.title = 'By Group'
    ncols = 6
    row = _write_xl_header(ws, classroom, extra, 'Group Work Analytics — By Group', ncols)
    headers = ['Group', 'Stream', 'Assignments', 'Best %', 'Worst %', 'Average %']
    for i, h in enumerate(headers, start=1):
        c = ws.cell(row, i, h)
        c.font = Font(bold=True, color='FFFFFFFF', size=10)
        c.fill = _fill('FF111827')
        c.alignment = Alignment(horizontal='center')
        c.border = _thin_border()
    row += 1
    for g in analytics.get('per_group', []):
        values = [g['group_name'], g['stream_name'] or '—', g['assignments_count'],
                  f"{g['best_pct']}%", f"{g['worst_pct']}%", f"{g['average_pct']}%"]
        for i, v in enumerate(values, start=1):
            c = ws.cell(row, i, v)
            c.border = _thin_border()
            c.alignment = Alignment(horizontal='center' if i > 1 else 'left')
        ws.cell(row, 1).font = Font(bold=True, color='FF111827')
        fill, font = _pct_fill_font(g['average_pct'])
        avg_cell = ws.cell(row, 6)
        avg_cell.font = font
        if fill:
            avg_cell.fill = fill
        row += 1
    row += 1
    _write_xl_footer(ws, row, ncols)
    for i, w in enumerate([24, 16, 13, 10, 10, 12], start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    # ── Sheet 2: By Stream ───────────────────────────────────────────
    ws2 = wb.create_sheet('By Stream')
    ncols2 = 4
    row = _write_xl_header(ws2, classroom, extra, 'Group Work Analytics — By Stream', ncols2)
    headers = ['Stream', 'Groups', 'Assignments Scored', 'Average %']
    for i, h in enumerate(headers, start=1):
        c = ws2.cell(row, i, h)
        c.font = Font(bold=True, color='FFFFFFFF', size=10)
        c.fill = _fill('FF111827')
        c.alignment = Alignment(horizontal='center')
        c.border = _thin_border()
    row += 1
    for s in analytics.get('per_stream', []):
        values = [s['stream_name'], s['group_count'], s['assignments_scored'], f"{s['average_pct']}%"]
        for i, v in enumerate(values, start=1):
            c = ws2.cell(row, i, v)
            c.border = _thin_border()
            c.alignment = Alignment(horizontal='center' if i > 1 else 'left')
        ws2.cell(row, 1).font = Font(bold=True, color='FF111827')
        fill, font = _pct_fill_font(s['average_pct'])
        avg_cell = ws2.cell(row, 4)
        avg_cell.font = font
        if fill:
            avg_cell.fill = fill
        row += 1
    row += 1
    _write_xl_footer(ws2, row, ncols2)
    for i, w in enumerate([20, 10, 18, 12], start=1):
        ws2.column_dimensions[get_column_letter(i)].width = w

    # ── Sheet 3: Trend ───────────────────────────────────────────────
    ws3 = wb.create_sheet('Trend')
    ncols3 = 5
    row = _write_xl_header(ws3, classroom, extra, 'Group Work Analytics — Assignment Trend', ncols3)
    headers = ['Date', 'Assignment', 'Type', 'Groups Scored', 'Average %']
    for i, h in enumerate(headers, start=1):
        c = ws3.cell(row, i, h)
        c.font = Font(bold=True, color='FFFFFFFF', size=10)
        c.fill = _fill('FF111827')
        c.alignment = Alignment(horizontal='center')
        c.border = _thin_border()
    row += 1
    for t_row in analytics.get('trend', []):
        values = [t_row['date'], t_row['title'], t_row['assignment_type'],
                  t_row['groups_scored'], f"{t_row['average_pct']}%"]
        for i, v in enumerate(values, start=1):
            c = ws3.cell(row, i, v)
            c.border = _thin_border()
            c.alignment = Alignment(horizontal='center' if i not in (2,) else 'left')
        fill, font = _pct_fill_font(t_row['average_pct'])
        avg_cell = ws3.cell(row, 5)
        avg_cell.font = font
        if fill:
            avg_cell.fill = fill
        row += 1
    row += 1
    _write_xl_footer(ws3, row, ncols3)
    for i, w in enumerate([14, 30, 14, 15, 12], start=1):
        ws3.column_dimensions[get_column_letter(i)].width = w

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()


def generate_groups_roster_excel(classroom, groups: list, extra: dict) -> bytes:
    wb = Workbook()
    ws = wb.active
    ws.title = 'Group Rosters'
    ncols = 5
    row = _write_xl_header(ws, classroom, extra, 'Group Rosters & Scores', ncols)

    for g in groups:
        # Group banner row, with badge image if available.
        ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
        title = g.name + (f'  ·  {g.subject.name}' if g.subject_id else '')
        c = ws.cell(row, 1, title)
        c.font = Font(bold=True, color='FFFFFFFF', size=12)
        c.fill = _fill(g.badge_color.replace('#', 'FF') if g.badge_color else 'FF2563eb')
        c.alignment = Alignment(horizontal='left', indent=2)
        ws.row_dimensions[row].height = 24
        badge_path = _badge_path(g)
        if badge_path:
            try:
                img = XLImage(badge_path)
                img.height, img.width = 28, 28
                img.anchor = f'A{row}'
                ws.add_image(img)
            except Exception:
                pass
        row += 1

        headers = ['#', 'Student Name', 'Student ID', 'Tier', 'Score %']
        for i, h in enumerate(headers, start=1):
            c = ws.cell(row, i, h)
            c.font = Font(bold=True, size=9, color='FFFFFFFF')
            c.fill = _fill('FF374151')
            c.border = _thin_border()
            c.alignment = Alignment(horizontal='center')
        row += 1

        members = sorted(g.memberships.all(), key=lambda m: -(m.average_at_placement or 0))
        if not members:
            ws.merge_cells(start_row=row, start_column=1, end_row=row, end_column=ncols)
            ws.cell(row, 1, 'No members yet').alignment = Alignment(horizontal='center')
            row += 1
        for i, m in enumerate(members, start=1):
            values = [i, m.student.full_name, m.student.student_id,
                      TIER_LABELS.get(m.tier, m.tier),
                      f'{m.average_at_placement}%' if m.average_at_placement is not None else '—']
            for col, v in enumerate(values, start=1):
                c = ws.cell(row, col, v)
                c.border = _thin_border()
                c.alignment = Alignment(horizontal='center' if col != 2 else 'left')
                if col == 4:
                    c.fill = _fill(TIER_COLORS_XL.get(m.tier, 'FFFFFFFF'))
                    c.font = Font(color='FFFFFFFF', bold=True, size=9)
            row += 1
        row += 1  # blank row between groups

    _write_xl_footer(ws, row, ncols)

    widths = [5, 26, 14, 16, 12]
    for i, w in enumerate(widths, start=1):
        ws.column_dimensions[get_column_letter(i)].width = w

    buf = io.BytesIO()
    wb.save(buf)
    return buf.getvalue()
