def _esc(v) -> str:
    """Escape a value before it's interpolated into ReportLab's mini-XML
    Paragraph markup. Any teacher-entered text (group names, badge
    labels, etc.) can contain '<', '>', or '&' — ordinary in a maths
    platform ("x < y", "Form 3 & 4") — and an unescaped one throws a
    ReportLab ParseError that 500s the whole export."""
    return _xml_escape(str(v))


def _badge_path(group):
    if not group.badge_image:
        return None
    try:
        path = group.badge_image.path
        return path if os.path.exists(path) else None
    except (ValueError, OSError):
        return None


def _meta_lines(classroom, extra: dict) -> list[str]:
    lines = [
        f'Class: {classroom}',
        f'Grade Level: {classroom.grade_level.name}',
        f'Academic Year: {extra.get("academic_year") or classroom.academic_year}',
    ]
    if extra.get('subject_name'):
        lines.append(f'Subject: {extra["subject_name"]}')
    if extra.get('term_display'):
        lines.append(f'Term: {extra["term_display"]}')
    lines.append(f'Generated: {datetime.now().strftime("%d %B %Y, %H:%M")}')
    if extra.get('generated_by'):
        lines.append(f'Generated by: {extra["generated_by"]}')
    return lines


